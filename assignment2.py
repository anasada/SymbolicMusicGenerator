def extract_map(midi_file):
  midi_obj = miditoolkit.midi.parser.MidiFile(midi_file)
  ticks_per_beat = midi_obj.ticks_per_beat
  notes = midi_obj.instruments[0].notes
  max_time = max(n.end for n in notes)

  examples = []
  for t in range(0, max_time, ticks_per_beat):
      chord_notes = [n.pitch for n in notes if n.start <= t < n.end]
      # Get chord
      if len(chord_notes) < 3:
          continue

      # Get melody (highest pitch in this window)
      window_notes = [n for n in notes if t <= n.start < t + ticks_per_beat]
      if not window_notes:
          continue
      melody_note = max(window_notes, key=lambda n: n.pitch).pitch

      examples.append((chord_notes, melody_note))
  return examples

