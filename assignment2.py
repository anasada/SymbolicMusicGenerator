def note_extraction(midi_file):
    midi = Score(midi_file)
    tokens = bigram_tokenizer(midi)[0].tokens
    pitch_list = []

    for event in tokens:
      if "Pitch" in event:
         num = "".join([c for c in event if c.isdigit()]) #extract digit
         pitch_list.append(int(num))
    return pitch_list

def note_frequency(midi_files):
    freqCount = {}
    for mFile in midi_files:
      pitch_list = note_extraction(mFile)
      for note in pitch_list:
        if note in freqCount:
          freqCount[note] += 1
        else:
          freqCount[note] = 1

    return freqCount

def note_unigram_probability(midi_files):
    note_counts = note_frequency(midi_files)
    unigramProbabilities = {}

    total = sum(note_counts.values())
    for key, value in note_counts.items():
      unigramProbabilities[key] = value/total

    return unigramProbabilities

def note_bigram_probability(midi_files):
    bigramTransitions = defaultdict(list)
    bigramTransitionProbabilities = defaultdict(list)

    #collect the bigrams
    bigrams = defaultdict(int)
    for mFile in midi_files:
      pitch_list = note_extraction(mFile)
      for (chord1,chord2) in zip(pitch_list[:-1],pitch_list[1:]):
        bigrams[(chord1,chord2)] += 1

    #use the bigrams (already unique and counted)
    transitionCounts = defaultdict(list)
    for key, value in bigrams.items():
      bigramTransitions[key[0]].append(key[1])
      transitionCounts[key[0]].append(value)

    #normalize counts into probabilities
    for key, value in transitionCounts.items():
      total = sum(value)
      for count in value:
        bigramTransitionProbabilities[key].append(count/total)

    return bigramTransitions, bigramTransitionProbabilities

def note_bigram_perplexity(midi_file):
    unigramProbabilities = note_unigram_probability(train_data)
    bigramTransitions, bigramTransitionProbabilities = note_bigram_probability(train_data)

    #sequence in midi file
    actual = note_extraction(midi_file)

    #prob get that sequence
    total = 0
    N = len(actual)
    for i in range(N):
      curr = actual[i]
      if i == 0:
        total += np.log(unigramProbabilities[curr]) #p(w1)
      else:
        prev = actual[i-1]
        for j in range(len(bigramTransitions[prev])):
          if bigramTransitions[prev][j] == curr: #aligning with probs list
            index = j
        total += np.log(bigramTransitionProbabilities[prev][index])

    #equation
    return (np.exp((-1/N)*total))

