def create_midi(chord_seq, melody_seq, output_path):
    midi_obj = miditoolkit.MidiFile()
    piano = miditoolkit.Instrument(program=0)  # Acoustic Grand Piano

    # Example: align chords and melody notes per timestep (assuming fixed duration)
    time_per_step = 480 * 3
    time = 0

    for chord_pcs, melody_pitches in zip(chord_seq, melody_seq):
        # Add chord notes
        for pc in chord_pcs:
            note = miditoolkit.Note(
                velocity=80,
                pitch=pc,
                start=time,
                end=time + time_per_step
            )
            piano.notes.append(note)

        # Add melody notes consecutively within the chord step
        num_notes = len(melody_pitches)
        if num_notes > 0:
            note_duration = time_per_step // num_notes
            for i, pitch in enumerate(melody_pitches):
                if pitch >= 0:
                    note = miditoolkit.Note(
                        velocity=100,
                        pitch=pitch,
                        start=time + i * note_duration,
                        end=time + (i + 1) * note_duration
                    )
                    piano.notes.append(note)

        time += time_per_step

    midi_obj.instruments.append(piano)
    midi_obj.dump(output_path)

