class HarmonyRNN(nn.Module):
    def __init__(self, chord_vocab_size, embedding_dim, hidden_dim, num_layers, melody_vocab_size):
        super(HarmonyRNN, self).__init__()
        self.embedding = nn.Embedding(chord_vocab_size, embedding_dim)
        self.rnn = nn.LSTM(
            input_size=embedding_dim,
            hidden_size=hidden_dim,
            num_layers=num_layers,
            batch_first=True
        )
        self.fc1 = nn.Linear(hidden_dim, hidden_dim // 2)
        self.fc2 = nn.Linear(hidden_dim // 2, melody_vocab_size)

