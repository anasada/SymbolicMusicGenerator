def generate_melody(model, chord_sequence, temperature=1.0, device='cuda'):
    model.eval()
    chord_sequence = torch.tensor(chord_sequence, device=device).unsqueeze(0)  # (1, seq_len)

    with torch.no_grad():
        outputs, _ = model(chord_sequence)  # (1, seq_len, melody_vocab_size)
        logits = outputs.squeeze(0)  # (seq_len, melody_vocab_size)
        logits = logits / temperature
        probs = torch.softmax(logits, dim=-1)
        melody_tokens = torch.multinomial(probs, num_samples=1).squeeze(-1)  # (seq_len)

    return melody_tokens.cpu().tolist()

