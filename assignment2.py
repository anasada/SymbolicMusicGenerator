def evaluate_perplexity2(model, data_loader, melody_vocab_size=88, device='cuda'):
    model.eval()
    total_loss = 0.0
    total_tokens = 0
    criterion = nn.CrossEntropyLoss(reduction='sum')

    with torch.no_grad():
        for batch in data_loader:
            chords = batch['chords'].to(device)
            melodies = batch['melodies'].to(device)

            outputs, _ = model(chords)
            outputs = outputs.reshape(-1, melody_vocab_size)
            targets = melodies.reshape(-1)

            loss = criterion(outputs, targets)
            total_loss += loss.item()
            total_tokens += targets.size(0)

    avg_loss = total_loss / total_tokens
    perplexity = math.exp(avg_loss)
    return perplexity

